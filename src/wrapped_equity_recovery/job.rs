    #[tokio::test]
    async fn enqueue_dedup_matches_symbol_exactly_not_as_substring() {
        let apalis_pool = crate::test_utils::setup_test_apalis_pool().await;

        let mut queue = WrappedEquityRecoveryJobQueue::new(&apalis_pool);
        queue
            .push(WrappedEquityRecoveryJob {
                chain: Chain::Base,
                symbol: Symbol::new("GOOGL").unwrap(),
                recovery_id: WrappedEquityRecoveryId(Uuid::new_v4()),
                backpressure_streak: BackpressureStreak::default(),
            })
            .await
            .unwrap();

        // The exact query the reactor uses to dedupe wrapped-recovery enqueues.
        const DEDUP_QUERY: &str = "SELECT COUNT(*) FROM Jobs \
             WHERE job_type = ? \
             AND status IN ('Pending', 'Queued', 'Running') \
             AND json_extract(job, '$.symbol') = ?";
        let job_type = std::any::type_name::<WrappedEquityRecoveryJob>();

        let (exact,): (i64,) = sqlx_apalis::query_as(DEDUP_QUERY)
            .bind(job_type)
            .bind("GOOGL")
            .fetch_one(&apalis_pool)
            .await
            .unwrap();
        assert_eq!(exact, 1, "exact symbol must match the queued GOOGL job");

        let (substring,): (i64,) = sqlx_apalis::query_as(DEDUP_QUERY)
            .bind(job_type)
            .bind("GOOG")
            .fetch_one(&apalis_pool)
            .await
            .unwrap();
        assert_eq!(
            substring, 0,
            "a substring ticker (GOOG) must not match the queued GOOGL job",
        );
    }

    /// Acceptance criterion (ADR 0017 SS4): a bot-gas receipt cost enqueue
    /// failure on `ConfirmOrphanDeposit` must delayed-redrive the job rather
    /// than propagate terminally -- otherwise a bookkeeping write can consume
    /// the apalis retry budget and open this supervised worker's fail-stop
    /// circuit. The confirm already succeeded on-chain and the aggregate has
    /// not advanced past `OrphanDepositSubmitted`, so redriving is safe.
