/// Apalis queue type for [`WrappedEquityRecoveryJob`].
pub(crate) type WrappedEquityRecoveryJobQueue = JobQueue<WrappedEquityRecoveryJob>;

/// Dependencies the recovery job needs to claim the per-symbol concurrency
/// guard, read inventory, and send commands through the aggregate's store.
/// Services (raindex/wrapper/transfer) live on the store -- not here.
pub(crate) struct WrappedEquityRecoveryCtx {
    pub(crate) inventory: Arc<BroadcastingInventory>,
    pub(crate) store: Arc<Store<WrappedEquityRecovery>>,
    pub(crate) mint_store: Arc<Store<TokenizedEquityMint>>,
    pub(crate) redemption_store: Arc<Store<EquityRedemption>>,
    pub(crate) equity_in_progress: Arc<RwLock<HashMap<Symbol, GuardState>>>,
    /// Queue used for delayed self-reschedule when the shared equity guard is
    /// held by another recovery/transfer job.
    pub(crate) queue: WrappedEquityRecoveryJobQueue,
    pub(crate) reschedule_interval: Duration,
}

/// Why a single recovery job attempt failed. Errors propagate up through
/// apalis; most service-call failures inside the aggregate's command
/// handlers are recorded as `RecoveryFailed` events and don't surface here.
/// The one exception is a bot-gas enqueue failure
/// (`WrappedEquityRecoveryError::BotGasEnqueueFailed`), which the aggregate
/// deliberately propagates so it reaches `finish`'s
/// `redrive_on_bot_gas_failure` call instead of permanently failing the
/// recovery over a best-effort accounting write.
#[derive(Debug, Error)]
pub(crate) enum WrappedEquityRecoveryJobError {
    #[error("recovery aggregate error: {0}")]
    Aggregate(#[from] SendError<WrappedEquityRecovery>),
    #[error(transparent)]
    Domain(#[from] WrappedEquityRecoveryError),
    #[error(
        "inventory view reports both an active mint ({mint_id}) and active redemption \
         ({redemption_id}) for symbol {symbol} -- aborting recovery"
    )]
    ConflictingActiveTransfers {
        symbol: Symbol,
        mint_id: IssuerRequestId,
        redemption_id: RedemptionAggregateId,
    },
    #[error(
        "active mint {mint_id} for symbol {symbol} carries quantity {aggregate_shares}, \
         which does not match the wrapped-equity wallet snapshot {snapshot_shares} -- \
         refusing to dispatch to a stale aggregate"
    )]
    ActiveMintQuantityMismatch {
        symbol: Symbol,
        mint_id: IssuerRequestId,
        snapshot_shares: FractionalShares,
        aggregate_shares: FractionalShares,
    },
    #[error(
        "active redemption {redemption_id} for symbol {symbol} carries quantity \
         {aggregate_shares}, which does not match the wrapped-equity wallet snapshot \
         {snapshot_shares} -- refusing to dispatch to a stale aggregate"
    )]
    ActiveRedemptionQuantityMismatch {
        symbol: Symbol,
        redemption_id: RedemptionAggregateId,
        snapshot_shares: FractionalShares,
        aggregate_shares: FractionalShares,
    },
    #[error(
        "{symbol} has an active {transfer} on {transfer_chain}, but this recovery runs on \
         {recovery_chain} -- waiting for that transfer instead of dispatching across chains"
    )]
    ActiveTransferOnOtherChain {
        symbol: Symbol,
        transfer: String,
        transfer_chain: Chain,
        recovery_chain: Chain,
    },
    #[error("active mint {mint_id} for symbol {symbol} is missing from the mint store")]
    ActiveMintMissing {
        symbol: Symbol,
        mint_id: IssuerRequestId,
    },
    #[error(
        "active redemption {redemption_id} for symbol {symbol} is missing from the \
         redemption store"
    )]
    ActiveRedemptionMissing {
        symbol: Symbol,
        redemption_id: RedemptionAggregateId,
    },
    #[error("active mint store error: {0}")]
    ActiveMintAggregate(
        #[from]
        st0x_event_sorcery::AggregateError<
            st0x_event_sorcery::LifecycleError<crate::tokenized_equity_mint::TokenizedEquityMint>,
        >,
    ),
    #[error("active redemption store error: {0}")]
    ActiveRedemptionAggregate(
        #[from]
        st0x_event_sorcery::AggregateError<
            st0x_event_sorcery::LifecycleError<crate::equity_redemption::EquityRedemption>,
        >,
    ),
    #[error("failed to reschedule recovery job after guard contention: {0}")]
    Reschedule(#[from] QueuePushError),
}

/// Apalis job payload. The reactor pushes one of these per symbol and chain
/// with a positive wrapped wallet balance, generating a fresh
/// `recovery_id` at push time so apalis retries hit the same aggregate.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct WrappedEquityRecoveryJob {
    /// The chain whose wallet holds the shares. Rows queued before jobs
    /// named their chain ran on Base.
    #[serde(default = "crate::onchain::legacy_chain")]
    pub(crate) chain: Chain,
    pub(crate) symbol: Symbol,
    pub(crate) recovery_id: WrappedEquityRecoveryId,
    /// Count of consecutive broker rate-limit (429) reschedules leading up to
    /// this attempt (RAI-1494). `#[serde(default)]` so a row enqueued under
    /// the pre-this-change payload shape still deserializes to `0` instead of
    /// crashing the poll stream's `sqlx::Decode`.
    ///
    /// NOT YET wired to a reschedule: `resume_mint`/`resume_redemption`
    /// failures are caught inside the aggregate's command handler and
    /// recorded as a terminal `RecoveryFailed` event with only a
    /// Display-formatted `String` reason (see `resume_mint_or_fail` /
    /// `resume_redemption_or_fail` in `aggregate.rs`) -- `ctx.store.send()`
    /// therefore returns `Ok(())` regardless, so `perform()` never observes
    /// an `Err` to classify for this failure class, and `find_backpressure`
    /// cannot walk to a real Alpaca error type from any constructible
    /// `WrappedEquityRecoveryJobError` today. This is pre-existing behavior,
    /// not a regression: a 429 here has always immediately terminalized the
    /// recovery with zero retries. Closing this gap needs the aggregate's
    /// error type to preserve the classified error (not just its Display
    /// string) and `transition()` to return `Err` instead of
    /// `Ok(RecoveryFailed)` on a classified 429, plus threading this streak
    /// into the `Command` (the aggregate has no visibility into the job's own
    /// payload) -- a redesign of the aggregate's error contract, out of scope
    /// for this task's per-job wiring. Field added now so the payload schema
    /// is ready when that follow-up lands.
    #[serde(default)]
    pub(crate) backpressure_streak: BackpressureStreak,
}

impl Job<WrappedEquityRecoveryCtx> for WrappedEquityRecoveryJob {
    type Output = ();
    type Error = WrappedEquityRecoveryJobError;

    const WORKER_NAME: &'static str = "wrapped-equity-recovery-worker";

    const PERFORM_TIMEOUT: Option<std::time::Duration> =
        Some(crate::conductor::job::DEFAULT_PERFORM_TIMEOUT);

    #[cfg(any(test, feature = "test-support"))]
    const JOB_KIND: crate::conductor::job::JobKind =
        crate::conductor::job::JobKind::WrappedEquityRecovery;

    fn label(&self) -> Label {
        Label::new(format!(
            "WrappedEquityRecovery:{}:{}:{}",
            self.chain, self.symbol, self.recovery_id
        ))
    }

    async fn perform(&self, ctx: &WrappedEquityRecoveryCtx) -> Result<Self::Output, Self::Error> {
        let symbol = self.symbol.clone();

        let current_state = ctx.store.load(&self.recovery_id).await?;
        if let Some(state) = &current_state
            && state.chain() != self.chain
        {
            if !state.is_terminal() {
                fail_on_chain_mismatch(ctx, self, state.chain()).await?;
            }
            return Ok(());
        }

        // Two-path claim: this job handles a positive wrapped wallet
        // balance, which can be either an orphan (absent guard) or the
        // landed-but-unconfirmed `WrapSubmitted` outcome -- the wrap tx
        // actually landed so the tokens are WRAPPED, but the confirmation read
        // failed and the transfer job handed the slot to recovery as
        // `HeldForRecovery`. Claiming `HeldForRecovery` here is what drains that
        // slot; refusing it (as the old orphan-only claim did) left it wedged
        // because `UnwrappedEquityRecovery` `NoBalanceSkip`s on a wrapped
        // balance. The atomic claim makes a concurrent `UnwrappedEquityRecovery`
        // claim safe -- only one wins, the other reschedules. Returns None only
        // for `ActiveTransfer` (a live transfer job owns the slot) or a
        // `HeldForRecovery` of another chain.
        let Some(guard) =
            claim_guard_for_recovery_or_orphan(&ctx.equity_in_progress, &symbol, self.chain)
        else {
            debug!(
                target: "rebalance",
                chain = %self.chain,
                %symbol,
                recovery_id = %self.recovery_id,
                "Rescheduling wrapped equity recovery: equity_in_progress held by \
                 active transfer or another chain's recovery; deferring",
            );
            ctx.queue
                .clone()
                .push_with_delay(self.clone(), ctx.reschedule_interval)
                .await?;
            return Ok(());
        };

        let mut detected_shares = None;
        if let Some(agg) = ctx.store.load(&self.recovery_id).await? {
            if let WrappedEquityRecovery::Failed {
                detection_failure: Some(disposition),
                ..
            } = &agg
            {
                match disposition {
                    DetectionFailureDisposition::RestartDetection => {
                        self.enqueue_fresh_recovery(ctx).await?;
                    }
                    DetectionFailureDisposition::PreserveHold => {}
                }
                return Ok(());
            }
            if agg.is_terminal() {
                debug!(
                    target: "rebalance",
                    %symbol,
                    recovery_id = %self.recovery_id,
                    "Skipping wrapped equity recovery: aggregate already terminal",
                );
                guard.release();
                return Ok(());
            }

            // Resume dispatch on the current non-terminal state. Enumerated
            // explicitly (no `_` arm) -- mirroring `UnwrappedEquityRecoveryJob`
            // -- so a new non-terminal `WrappedEquityRecovery` state fails to
            // compile here until it is deliberately wired into a resume path,
            // instead of silently falling through to the no-op below.
            match agg {
                // Resume point for a redrive after this attempt's
                // ConfirmOrphanDeposit failed only to enqueue its bot-gas cost
                // (see `is_bot_gas_enqueue_failure` below): the deposit is
                // already confirmed on-chain, so the redriven attempt must
                // re-send ConfirmOrphanDeposit directly, NOT `Detect` --
                // resending `Detect` on an already-initialized aggregate is
                // rejected with `AlreadyInitialized`.
                WrappedEquityRecovery::OrphanDepositSubmitted { .. } => {
                    let result = ctx
                        .store
                        .send(
                            &self.recovery_id,
                            WrappedEquityRecoveryCommand::ConfirmOrphanDeposit,
                        )
                        .await
                        .map_err(Into::into);
                    return finish(ctx, self, guard, result).await;
                }
                // `Detected` has no persisted dispatch decision yet: a job
                // retried after `Detect` succeeded re-derives the
                // mint/redemption/orphan path from `InventoryView` below and
                // skips `Detect`, which an initialized aggregate refuses.
                WrappedEquityRecovery::Detected { shares, .. } => detected_shares = Some(shares),
                // `DispatchedToMint`/`DispatchedToRedemption`/`OrphanDeposited`/
                // `Failed` are already short-circuited by the `is_terminal`
                // early return above; enumerated here (rather than folded into
                // `_`) so this match stays exhaustive and a new non-terminal
                // state fails to compile until it is deliberately wired into a
                // resume arm above.
                WrappedEquityRecovery::DispatchedToMint { .. }
                | WrappedEquityRecovery::DispatchedToRedemption { .. }
                | WrappedEquityRecovery::OrphanDeposited { .. }
                | WrappedEquityRecovery::Failed { .. } => {}
            }
        }

        let Some(snapshot) = read_recovery_snapshot(&ctx.inventory, self.chain, &symbol).await
        else {
            // No wrapped balance to drain this cycle. Do NOT release the guard:
            // an orphan claim drops to absent (the reactor re-triggers on the
            // next positive-balance poll), while a `HeldForRecovery` claim drops
            // back to `HeldForRecovery`. The reactor only re-dispatches on a
            // POSITIVE balance, so a `HeldForRecovery`-origin claim that finds
            // zero balance must self-reschedule or the slot wedges with no job
            // left to drain it.
            if detected_shares.is_some() && !guard.claimed_from_held_for_recovery() {
                // The detected balance is gone, so this recovery can never
                // dispatch; fail it so it does not stay open forever. A
                // later positive balance opens a new recovery.
                warn!(
                    target: "rebalance",
                    %symbol,
                    recovery_id = %self.recovery_id,
                    "Failing detected wrapped equity recovery: wrapped balance is gone",
                );
                ctx.store
                    .send(
                        &self.recovery_id,
                        WrappedEquityRecoveryCommand::FailRecovery {
                            reason: "wrapped balance gone before dispatch".to_owned(),
                        },
                    )
                    .await?;
                guard.release();
            } else if guard.claimed_from_held_for_recovery() {
                debug!(
                    target: "rebalance",
                    %symbol,
                    recovery_id = %self.recovery_id,
                    "Rescheduling wrapped equity recovery: no positive balance yet but slot \
                     is HeldForRecovery; re-enqueueing with delay to keep polling until the \
                     balance resolves or the slot is cleared",
                );
                ctx.queue
                    .clone()
                    .push_with_delay(self.clone(), ctx.reschedule_interval)
                    .await?;
            } else {
                debug!(
                    target: "rebalance",
                    %symbol,
                    recovery_id = %self.recovery_id,
                    "Skipping wrapped equity recovery: no positive balance in inventory view; \
                     orphan claim, guard drop removes entry so future inventory polls can \
                     re-trigger recovery",
                );
            }
            return Ok(());
        };

        // A resumed `Detected` record deposits the shares it stored, so a
        // changed balance makes it stale: fail it and queue a fresh recovery
        // for the current balance, even when polling suppresses unchanged reads.
        if let Some(detected) = detected_shares
            && snapshot.shares != detected
        {
            return self
                .fail_stale_detected(
                    ctx,
                    format!(
                        "wrapped balance changed since detection: detected {detected}, \
                         current {}",
                        snapshot.shares
                    ),
                )
                .await;
        }

        if let Err(error) =
            validate_active_aggregate_quantity(ctx, self.chain, &symbol, &snapshot).await
        {
            if detected_shares.is_some() && error.is_business_validation() {
                return self.fail_invalid_detection(ctx, &error).await;
            }
            return wait_or_retry_after_validation(ctx, self, error).await;
        }

        if detected_shares.is_none() {
            let detected = ctx
                .store
                .send(
                    &self.recovery_id,
                    WrappedEquityRecoveryCommand::Detect {
                        chain: self.chain,
                        symbol: symbol.clone(),
                        shares: snapshot.shares,
                    },
                )
                .await;
            if let Err(error) = detected {
                return finish(ctx, self, guard, Err(error.into())).await;
            }
        }

        info!(
            target: "rebalance",
            %symbol,
            recovery_id = %self.recovery_id,
            shares = %snapshot.shares,
            ?snapshot.dispatch,
            "Wrapped equity recovery: dispatched detection",
        );

        self.dispatch(ctx, guard, snapshot).await
    }
}

impl WrappedEquityRecoveryJob {
    async fn fail_invalid_detection(
        &self,
        ctx: &WrappedEquityRecoveryCtx,
        error: &WrappedEquityRecoveryJobError,
    ) -> Result<(), WrappedEquityRecoveryJobError> {
        error!(
            target: "operational_alert",
            alert = true,
            chain = %self.chain,
            symbol = %self.symbol,
            recovery_id = %self.recovery_id,
            %error,
            "Wrapped equity recovery requires operator intervention: active aggregate \
             validation failed; closing the detection and retaining any existing hold"
        );
        ctx.store
            .send(
                &self.recovery_id,
                WrappedEquityRecoveryCommand::FailInvalidDetection {
                    reason: error.to_string(),
                },
            )
            .await?;
        Ok(())
    }

    /// Fails a resumed `Detected` record whose premise no longer holds. The
    /// caller's guard drops to its claim origin. A fresh job reads the current
    /// balance without relying on another wallet snapshot event.
    async fn fail_stale_detected(
        &self,
        ctx: &WrappedEquityRecoveryCtx,
        reason: String,
    ) -> Result<(), WrappedEquityRecoveryJobError> {
        warn!(
            target: "rebalance",
            chain = %self.chain,
            symbol = %self.symbol,
            recovery_id = %self.recovery_id,
            %reason,
            "Failing stale detected wrapped equity recovery on resume",
        );
        ctx.store
            .send(
                &self.recovery_id,
                WrappedEquityRecoveryCommand::FailStaleDetection { reason },
            )
            .await?;
        self.enqueue_fresh_recovery(ctx).await
    }

    async fn enqueue_fresh_recovery(
        &self,
        ctx: &WrappedEquityRecoveryCtx,
    ) -> Result<(), WrappedEquityRecoveryJobError> {
        ctx.queue
            .clone()
            .push_idempotent_with_delay(
                &format!("wrapped-recovery-replacement:{}", self.recovery_id),
                Self {
                    recovery_id: WrappedEquityRecoveryId(uuid::Uuid::new_v4()),
                    ..self.clone()
                },
                ctx.reschedule_interval,
            )
            .await?;
        Ok(())
    }

    /// Sends the dispatch command for a detected recovery and settles the
    /// guard through `finish`.
    async fn dispatch(
        &self,
        ctx: &WrappedEquityRecoveryCtx,
        guard: RecoveryGuard,
        snapshot: RecoverySnapshot,
    ) -> Result<(), WrappedEquityRecoveryJobError> {
        let symbol = &self.symbol;
        let result = match snapshot.dispatch {
            DispatchDecision::ActiveMint(mint_id) => ctx
                .store
                .send(
                    &self.recovery_id,
                    WrappedEquityRecoveryCommand::DispatchToMint { mint_id },
                )
                .await
                .map_err(Into::into),
            DispatchDecision::ActiveRedemption(redemption_id) => ctx
                .store
                .send(
                    &self.recovery_id,
                    WrappedEquityRecoveryCommand::DispatchToRedemption { redemption_id },
                )
                .await
                .map_err(Into::into),
            DispatchDecision::Orphan => {
                ctx.store
                    .send(
                        &self.recovery_id,
                        WrappedEquityRecoveryCommand::SubmitOrphanDeposit,
                    )
                    .await?;
                if let Some(agg) = ctx.store.load(&self.recovery_id).await?
                    && agg.is_terminal()
                {
                    Ok(())
                } else {
                    ctx.store
                        .send(
                            &self.recovery_id,
                            WrappedEquityRecoveryCommand::ConfirmOrphanDeposit,
                        )
                        .await
                        .map_err(Into::into)
                }
            }
            // Rejected by `validate_active_aggregate_quantity` before
            // `Detect`; never dispatched across chains.
            DispatchDecision::BusyOnOtherChain {
                transfer,
                transfer_chain,
            } => Err(WrappedEquityRecoveryJobError::ActiveTransferOnOtherChain {
                symbol: symbol.clone(),
                transfer,
                transfer_chain,
                recovery_chain: self.chain,
            }),
            DispatchDecision::Conflict {
                mint_id,
                redemption_id,
            } => {
                let reason = format!(
                    "InventoryView reports active mint {mint_id} and active redemption \
                     {redemption_id} for symbol {symbol}; refusing to dispatch"
                );
                warn!(target: "rebalance", %symbol, %mint_id, %redemption_id, "Wrapped equity recovery: conflict");
                ctx.store
                    .send(
                        &self.recovery_id,
                        WrappedEquityRecoveryCommand::FailRecovery { reason },
                    )
                    .await?;
                // Aggregate is now terminal (FailRecovery). Release the guard
                // directly here so future transfers are not permanently blocked.
                guard.release();
                return Err(WrappedEquityRecoveryJobError::ConflictingActiveTransfers {
                    symbol: symbol.clone(),
                    mint_id,
                    redemption_id,
                });
            }
        };

        finish(ctx, self, guard, result).await
    }
}

/// Handles a dispatch that failed validation before `Detect`. The guard
/// drops either way, restoring its claim origin (orphan removes the entry;
/// `HeldForRecovery` restores `HeldForRecovery`).
async fn wait_or_retry_after_validation(
    ctx: &WrappedEquityRecoveryCtx,
    job: &WrappedEquityRecoveryJob,
    error: WrappedEquityRecoveryJobError,
) -> Result<(), WrappedEquityRecoveryJobError> {
    if let WrappedEquityRecoveryJobError::ActiveTransferOnOtherChain { .. } = error {
        // Another chain's transfer owns the symbol. Record nothing and wait:
        // dispatching would resume that transfer from this chain's recovery,
        // and the orphan path would treat its tokens as abandoned.
        error!(
            target: "operational_alert",
            alert = true,
            chain = %job.chain,
            symbol = %job.symbol,
            recovery_id = %job.recovery_id,
            %error,
            "Rescheduling wrapped equity recovery: the symbol's active transfer is \
             on another chain",
        );
        ctx.queue
            .clone()
            .push_with_delay(job.clone(), ctx.reschedule_interval)
            .await?;
        return Ok(());
    }

    warn!(
        target: "rebalance",
        symbol = %job.symbol,
        recovery_id = %job.recovery_id,
        %error,
        "Wrapped equity recovery: active aggregate quantity mismatch; \
         skipping dispatch",
    );
    // A quantity mismatch is retryable.
    Err(error)
}

/// Releases or restores the per-symbol guard based on the dispatch outcome
/// and, on a bot-gas enqueue failure, redrives `job` with a delay instead of
/// propagating the error terminally. Shared by the fresh-dispatch path and
/// the `OrphanDepositSubmitted` resume path so both apply the identical
/// success/redrive/failure handling.
async fn finish(
    ctx: &WrappedEquityRecoveryCtx,
    job: &WrappedEquityRecoveryJob,
    guard: RecoveryGuard,
    result: Result<(), WrappedEquityRecoveryJobError>,
) -> Result<(), WrappedEquityRecoveryJobError> {
    // Release the guard on success (removes the slot). On a bot-gas
    // bookkeeping failure the shared `redrive_on_bot_gas_failure` mechanism
    // redrives via `ctx.queue` without releasing the guard, so the slot
    // drops normally (an orphan-origin claim removes the entry, while a
    // HeldForRecovery-origin claim restores HeldForRecovery) exactly as any
    // other retryable failure would -- the confirm step the failure follows
    // already succeeded onchain and the aggregate has not advanced past it,
    // so redriving the same command is safe. A recovery whose chain has no
    // services reschedules the same way, keeping the guard's claim origin.
    // Any other failure propagates.
    match result {
        Ok(()) => {
            guard.release();
            Ok(())
        }
        Err(error) if error.is_mint_resume_pending() => {
            warn!(%error, "Mint recovery remains pending; retaining ownership and retrying");
            ctx.queue
                .clone()
                .push_with_delay(job.clone(), ctx.reschedule_interval)
                .await?;
            Ok(())
        }
        Err(error) if error.is_chain_services_missing() => {
            error!(
                target: "operational_alert",
                alert = true,
                chain = %job.chain,
                symbol = %job.symbol,
                recovery_id = %job.recovery_id,
                %error,
                "Wrapped equity recovery cannot run: its chain has no equity services; \
                 rescheduling until the chain is wired again",
            );
            ctx.queue
                .clone()
                .push_with_delay(job.clone(), ctx.reschedule_interval)
                .await?;
            Ok(())
        }
        Err(error) => {
            redrive_on_bot_gas_failure(job, &ctx.queue, ctx.reschedule_interval, error).await
        }
    }
}

/// Fails a recovery whose record names another chain than the job that
/// resumed it. Driving it would act on one chain's wallet from the other
/// chain's job, so the record is closed and a fresh detection starts over.
async fn fail_on_chain_mismatch(
    ctx: &WrappedEquityRecoveryCtx,
    job: &WrappedEquityRecoveryJob,
    recorded_chain: Chain,
) -> Result<(), WrappedEquityRecoveryJobError> {
    let reason = format!(
        "recovery is recorded on {recorded_chain} but its job runs on {}",
        job.chain
    );
    error!(
        target: "rebalance",
        symbol = %job.symbol,
        recovery_id = %job.recovery_id,
        %recorded_chain,
        job_chain = %job.chain,
        "Wrapped equity recovery: chain mismatch between record and job; failing recovery",
    );
    ctx.store
        .send(
            &job.recovery_id,
            WrappedEquityRecoveryCommand::FailRecovery { reason },
        )
        .await?;
    Ok(())
}

impl WrappedEquityRecoveryJobError {
    fn is_mint_resume_pending(&self) -> bool {
        matches!(
            self,
            Self::Aggregate(AggregateError::UserError(LifecycleError::Apply(
                WrappedEquityRecoveryError::MintResumePending { .. }
            ))) | Self::Domain(WrappedEquityRecoveryError::MintResumePending { .. })
        )
    }

    /// The active mint or redemption no longer matches the wallet snapshot.
    /// A resumed record closes without queuing another invalid detection.
    fn is_business_validation(&self) -> bool {
        match self {
            Self::ActiveMintQuantityMismatch { .. }
            | Self::ActiveRedemptionQuantityMismatch { .. }
            | Self::ActiveMintMissing { .. }
            | Self::ActiveRedemptionMissing { .. } => true,
            Self::Aggregate(_)
            | Self::Domain(_)
            | Self::ConflictingActiveTransfers { .. }
            | Self::ActiveTransferOnOtherChain { .. }
            | Self::ActiveMintAggregate(_)
            | Self::ActiveRedemptionAggregate(_)
            | Self::Reschedule(_) => false,
        }
    }

    fn is_chain_services_missing(&self) -> bool {
        match self {
            Self::Aggregate(AggregateError::UserError(LifecycleError::Apply(
                WrappedEquityRecoveryError::ChainServicesMissing(_),
            )))
            | Self::Domain(WrappedEquityRecoveryError::ChainServicesMissing(_)) => true,
            Self::Aggregate(_)
            | Self::Domain(_)
            | Self::ConflictingActiveTransfers { .. }
            | Self::ActiveMintQuantityMismatch { .. }
            | Self::ActiveRedemptionQuantityMismatch { .. }
            | Self::ActiveMintMissing { .. }
            | Self::ActiveRedemptionMissing { .. }
            | Self::ActiveTransferOnOtherChain { .. }
            | Self::ActiveMintAggregate(_)
            | Self::ActiveRedemptionAggregate(_)
            | Self::Reschedule(_) => false,
        }
    }
}

impl BotGasFailureClassifier for WrappedEquityRecoveryJobError {
    fn is_bot_gas_enqueue_failure(&self) -> bool {
        match self {
            Self::Aggregate(AggregateError::UserError(LifecycleError::Apply(
                WrappedEquityRecoveryError::BotGasEnqueueFailed(_),
            )))
            | Self::Domain(WrappedEquityRecoveryError::BotGasEnqueueFailed(_)) => true,
            Self::Aggregate(_)
            | Self::Domain(_)
            | Self::ConflictingActiveTransfers { .. }
            | Self::ActiveMintQuantityMismatch { .. }
            | Self::ActiveRedemptionQuantityMismatch { .. }
            | Self::ActiveMintMissing { .. }
            | Self::ActiveRedemptionMissing { .. }
            | Self::ActiveTransferOnOtherChain { .. }
            | Self::ActiveMintAggregate(_)
            | Self::ActiveRedemptionAggregate(_)
            | Self::Reschedule(_) => false,
        }
    }
}

struct RecoverySnapshot {
    shares: st0x_execution::FractionalShares,
    dispatch: DispatchDecision,
}

#[derive(Debug)]
enum DispatchDecision {
    ActiveMint(IssuerRequestId),
    ActiveRedemption(RedemptionAggregateId),
    Orphan,
    /// `InventoryView` reports both an active mint and an active redemption
    /// for the same symbol. A symbol can only be in one in-flight transfer
    /// at a time -- this is a corrupt-state signal, not a normal dispatch
    /// path.
    Conflict {
        mint_id: IssuerRequestId,
        redemption_id: RedemptionAggregateId,
    },
    /// The symbol's active mint or redemption runs on another chain. The
    /// symbol is busy: this chain's wallet balance is neither that
    /// transfer's tokens nor an orphan while it runs.
    BusyOnOtherChain {
        transfer: String,
        transfer_chain: Chain,
    },
}

async fn read_recovery_snapshot(
    inventory: &BroadcastingInventory,
    chain: Chain,
    symbol: &Symbol,
) -> Option<RecoverySnapshot> {
    let view = inventory.read().await;
    let shares = view.inflight_equity_at(symbol, InFlightEquityLocation::WalletWrapped(chain))?;
    if shares == st0x_execution::FractionalShares::ZERO {
        return None;
    }
    let dispatch = decide_dispatch(&view, chain, symbol);
    drop(view);
    Some(RecoverySnapshot { shares, dispatch })
}

/// Confirms the active mint or redemption aggregate carries the same quantity
/// as the wrapped wallet snapshot. Without this check, the recovery stream
/// would record `snapshot.shares` for an aggregate that was actually set up
/// for a different amount, leaving the audit trail and the resumed work
/// disagreeing on how many shares moved.
///
/// A `WrapSubmitted` mint is exempt from the quantity check: its quantity is
/// in underlying shares, while the landed wrap left vault shares in the
/// wallet, and the two differ whenever the vault ratio is not 1. Dispatch only
/// resumes the mint, which reads the wrap receipt and deposits the share count
/// it reports.
async fn validate_active_aggregate_quantity(
    ctx: &WrappedEquityRecoveryCtx,
    chain: Chain,
    symbol: &Symbol,
    snapshot: &RecoverySnapshot,
) -> Result<(), WrappedEquityRecoveryJobError> {
    match &snapshot.dispatch {
        DispatchDecision::ActiveMint(mint_id) => {
            let mint = ctx.mint_store.load(mint_id).await?.ok_or_else(|| {
                WrappedEquityRecoveryJobError::ActiveMintMissing {
                    symbol: symbol.clone(),
                    mint_id: mint_id.clone(),
                }
            })?;
            if mint.chain() != chain {
                return Err(WrappedEquityRecoveryJobError::ActiveTransferOnOtherChain {
                    symbol: symbol.clone(),
                    transfer: format!("mint {mint_id}"),
                    transfer_chain: mint.chain(),
                    recovery_chain: chain,
                });
            }
            if matches!(mint, TokenizedEquityMint::WrapSubmitted { .. }) {
                return Ok(());
            }
            let aggregate_shares = FractionalShares::new(mint.quantity());
            if aggregate_shares != snapshot.shares {
                return Err(WrappedEquityRecoveryJobError::ActiveMintQuantityMismatch {
                    symbol: symbol.clone(),
                    mint_id: mint_id.clone(),
                    snapshot_shares: snapshot.shares,
                    aggregate_shares,
                });
            }
            Ok(())
        }
        DispatchDecision::ActiveRedemption(redemption_id) => {
            let redemption = ctx
                .redemption_store
                .load(redemption_id)
                .await?
                .ok_or_else(|| WrappedEquityRecoveryJobError::ActiveRedemptionMissing {
                    symbol: symbol.clone(),
                    redemption_id: redemption_id.clone(),
                })?;
            if redemption.chain() != chain {
                return Err(WrappedEquityRecoveryJobError::ActiveTransferOnOtherChain {
                    symbol: symbol.clone(),
                    transfer: format!("redemption {redemption_id}"),
                    transfer_chain: redemption.chain(),
                    recovery_chain: chain,
                });
            }
            let aggregate_shares = FractionalShares::new(redemption.quantity());
            if aggregate_shares != snapshot.shares {
                return Err(
                    WrappedEquityRecoveryJobError::ActiveRedemptionQuantityMismatch {
                        symbol: symbol.clone(),
                        redemption_id: redemption_id.clone(),
                        snapshot_shares: snapshot.shares,
                        aggregate_shares,
                    },
                );
            }
            Ok(())
        }
        DispatchDecision::BusyOnOtherChain {
            transfer,
            transfer_chain,
        } => Err(WrappedEquityRecoveryJobError::ActiveTransferOnOtherChain {
            symbol: symbol.clone(),
            transfer: transfer.clone(),
            transfer_chain: *transfer_chain,
            recovery_chain: chain,
        }),
        DispatchDecision::Orphan | DispatchDecision::Conflict { .. } => Ok(()),
    }
}

/// Picks the dispatch path for a wallet balance on `chain`. Only a transfer
/// on the same chain can own that balance; a transfer of the symbol on
/// another chain makes the symbol busy rather than the balance an orphan.
fn decide_dispatch(view: &InventoryView, chain: Chain, symbol: &Symbol) -> DispatchDecision {
    if let (Some((mint_id, _)), Some((redemption_id, _))) = (
        view.active_mint_with_chain(symbol),
        view.active_redemption_with_chain(symbol),
    ) {
        return DispatchDecision::Conflict {
            mint_id: mint_id.clone(),
            redemption_id: redemption_id.clone(),
        };
    }

    if let Some((mint_id, mint_chain)) = view.active_mint_with_chain(symbol)
        && mint_chain != chain
    {
        return DispatchDecision::BusyOnOtherChain {
            transfer: format!("mint {mint_id}"),
            transfer_chain: mint_chain,
        };
    }

    if let Some((redemption_id, redemption_chain)) = view.active_redemption_with_chain(symbol)
        && redemption_chain != chain
    {
        return DispatchDecision::BusyOnOtherChain {
            transfer: format!("redemption {redemption_id}"),
            transfer_chain: redemption_chain,
        };
    }

    match (
        view.active_mint_on(symbol, chain),
        view.active_redemption_on(symbol, chain),
    ) {
        (Some(mint_id), Some(redemption_id)) => DispatchDecision::Conflict {
            mint_id: mint_id.clone(),
            redemption_id: redemption_id.clone(),
        },
        (Some(mint_id), None) => DispatchDecision::ActiveMint(mint_id.clone()),
        (None, Some(redemption_id)) => DispatchDecision::ActiveRedemption(redemption_id.clone()),
        (None, None) => DispatchDecision::Orphan,
    }
}

